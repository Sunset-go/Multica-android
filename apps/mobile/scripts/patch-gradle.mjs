#!/usr/bin/env node
/**
 * Patch the generated `android/` directory with build fixes that are lost
 * when `expo prebuild` regenerates the directory.
 *
 * Fixes applied (all idempotent — safe to run repeatedly):
 *   1. gradle-wrapper.properties → force Gradle 9.5.0 (9.7.1+ bundles Kotlin 2.4.0
 *      which is incompatible with RN/Expo plugins compiled against Kotlin 2.1.x)
 *   2. gradle.properties → add `-Xskip-metadata-version-check` to work around
 *      Kotlin runtime 2.4.0 vs compiler 2.1.20 metadata mismatch in included builds;
 *      refresh the JDK path list; set `expo.useLegacyPackaging=true` so .so files
 *      are extracted next to each other (a DSO's `libc++_shared.so` dependency
 *      then resolves to the app's own copy instead of /system/lib64)
 *   3. build.gradle → force `org.jetbrains:annotations:23.0.0` to resolve
 *      version conflicts between AGP and Kotlin plugin transitive dependencies
 *   4. node_modules/@react-native/gradle-plugin/settings.gradle.kts → remove
 *      foojay-resolver-convention 0.5.0 (requires Gradle 9.8+ for IBM_SEMERU)
 *   5. node_modules/@react-native/gradle-plugin sub-module build files:
 *      jvmToolchain(17) -> jvmToolchain(21) (4 modules hardcode Java 17;
 *      most dev machines only have JDK 21, which is backwards-compatible)
 *   6. org.gradle.java.installations.paths → detected local JDKs (17 + 21)
 *   7. every Kotlin plugin build script in node_modules (RN / Expo / native
 *      modules) → add `-Xskip-metadata-version-check`; Gradle 9.5 bundles
 *      Kotlin 2.3.x stdlib while these plugins compile with 2.1.x
 *   8. app/build.gradle → point the CMake staging dir at <repo>/.cxx (Windows
 *      path-length limit) and apply scripts/android-fbjni-libcxx.gradle, which
 *      packages fbjni's own libc++_shared.so (react-android 0.83.6 ships one
 *      without `__cxa_init_primary_exception`, so the app crashed at startup)
 *
 * The generated `android/` directory is gitignored (root .gitignore →
 * `apps/mobile/android/` is regenerated by `expo prebuild`). This script
 * lives in `apps/mobile/scripts/` and is git-tracked, so the fixes survive
 * across fresh checkouts.
 *
 * Usage: called automatically by the build:android:apk script chain, after
 * `expo prebuild` has generated the directory.
 */
import {
  readFileSync,
  writeFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  realpathSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const mobileRoot = join(scriptDir, ".."); // apps/mobile
const androidDir = join(mobileRoot, "android");
const repoRoot = join(mobileRoot, "../.."); // repo root (pnpm workspace root)

/**
 * Resolve the JDK installations this build needs: a Java 17 toolchain for AGP
 * (javac/desugar) and the JDK running Gradle (21). Paths are detected instead
 * of hardcoded so a checkout on another drive/machine still builds.
 * Candidates: $JAVA_HOME, then common local install roots (including the
 * F:/Android toolchain this workspace installs to), then legacy dev paths.
 */
function resolveJdkPaths() {
  const fs = process.platform === "win32" ? ["bin", "java.exe"] : ["bin", "java"];
  const isJdk = (p) => existsSync(join(p, ...fs));
  const found = [];
  const push = (p) => {
    if (!p) return;
    const norm = p.replace(/\\/g, "/").replace(/\/+$/, "");
    if (isJdk(norm) && !found.includes(norm)) found.push(norm);
  };

  push(process.env.JAVA_HOME);

  // Versioned JDK roots: <root>/<jdk-17...>/bin/java
  const roots = ["F:/Android/jdk17", "D:/Scoop/apps/temurin17-jdk", "C:/Program Files/Eclipse Adoptium"];
  for (const root of roots) {
    if (!existsSync(root)) continue;
    push(root);
    push(join(root, "current"));
    let entries = [];
    try {
      entries = readdirSync(root);
    } catch {
      entries = [];
    }
    for (const name of entries) push(join(root, name));
  }

  push("D:/Java/jdk-21.0.11");
  push("D:/IDEA/JDK21.0.4");
  return found;
}
const rnSettingsKts = join(
  repoRoot,
  "node_modules/@react-native/gradle-plugin/settings.gradle.kts",
);

if (!existsSync(androidDir)) {
  console.error(
    `[patch-gradle] android/ not found at ${androidDir}\n` +
      "Run `pnpm -C apps/mobile exec expo prebuild --platform android` first.",
  );
  process.exit(1);
}

let patched = 0;

// --- Fix 1: Gradle wrapper → 9.5.0 ---
{
  const p = join(androidDir, "gradle", "wrapper", "gradle-wrapper.properties");
  if (existsSync(p)) {
    let content = readFileSync(p, "utf8");
    const targetUrl = "https\\://services.gradle.org/distributions/gradle-9.5.0-bin.zip";
    if (!content.includes("gradle-9.5.0-bin.zip")) {
      content = content.replace(
        /distributionUrl=.*gradle-[\d.]+-bin\.zip/,
        `distributionUrl=${targetUrl}`,
      );
      writeFileSync(p, content);
      patched++;
      console.log("[patch-gradle] pinned Gradle wrapper to 9.5.0");
    }
  } else {
    console.warn("[patch-gradle] gradle-wrapper.properties not found, skipping fix 1");
  }
}

// --- Fix 2: gradle.properties → -Xskip-metadata-version-check + JDK paths + newArchEnabled=false ---
{
  const p = join(androidDir, "gradle.properties");
  if (existsSync(p)) {
    let content = readFileSync(p, "utf8");
    let changed = false;
    if (!content.includes("-Xskip-metadata-version-check")) {
      content +=
        "\n" +
        "# Workaround: Gradle 9.5.0+ bundles Kotlin 2.4.0 but the RN/Expo plugins\n" +
        "# use Kotlin 2.1.x compiler; skip the metadata version check.\n" +
        "kotlin.options.freeCompilerArgs=-Xskip-metadata-version-check\n";
      changed = true;
    }
    const jdkPaths = resolveJdkPaths().join(",");
    if (!content.includes("org.gradle.java.installations.paths")) {
      content +=
        "\n" +
        "# Point Gradle to locally installed JDKs so toolchains can be resolved\n" +
        "# without foojay-resolver (which requires Gradle 9.8+).\n" +
        `org.gradle.java.installations.paths=${jdkPaths}\n`;
      changed = true;
    } else if (jdkPaths) {
      // Refresh a stale path list (prebuild regenerates this file).
      const next = content.replace(
        /^org\.gradle\.java\.installations\.paths=.*$/m,
        `org.gradle.java.installations.paths=${jdkPaths}`,
      );
      if (next !== content) {
        content = next;
        changed = true;
      }
    }
    // Extract native libs (useLegacyPackaging). Building with the libs left
    // inside the APK makes Android <= 10 resolve libfbjni.so's
    // `libc++_shared.so` dependency against /system/lib64, which lacks
    // `__cxa_init_primary_exception`; startup then crashes with
    // SoLoaderDSONotFoundError: couldn't find DSO to load: libfbjni.so.
    if (!content.includes("expo.useLegacyPackaging")) {
      content +=
        "\n" +
        "# Extract .so files to the app's native lib dir so libc++_shared.so\n" +
        "# resolves from the app instead of /system/lib64 (Android <= 10 crash).\n" +
        "expo.useLegacyPackaging=true\n";
      changed = true;
    } else if (/^expo\.useLegacyPackaging\s*=\s*false\s*$/m.test(content)) {
      content = content.replace(
        /^expo\.useLegacyPackaging\s*=\s*false\s*$/m,
        "expo.useLegacyPackaging=true",
      );
      changed = true;
    }
    // RN 0.82+ is new-architecture only: `newArchEnabled=false` prints an
    // error from the RN gradle plugin, so keep it (or restore it) at true.
    if (content.includes("newArchEnabled=false")) {
      content = content.replace(/newArchEnabled=false/, "newArchEnabled=true");
      changed = true;
    }
    if (changed) {
      writeFileSync(p, content);
      patched++;
      console.log("[patch-gradle] added compiler args + JDK paths + legacy packaging to gradle.properties");
    }
  } else {
    console.warn("[patch-gradle] gradle.properties not found, skipping fix 2");
  }
}

// --- Fix 3: root build.gradle → force org.jetbrains:annotations:23.0.0 ---
{
  const p = join(androidDir, "build.gradle");
  if (existsSync(p)) {
    let content = readFileSync(p, "utf8");
    if (!content.includes("force 'org.jetbrains:annotations:23.0.0'")) {
      // Insert resolutionStrategy block inside allprojects { repositories { ... } }
      // The generated build.gradle has an `allprojects` block with `repositories`.
      // We add a `configurations.all { resolutionStrategy { force ... } }` block.
      const marker = "allprojects {";
      const idx = content.indexOf(marker);
      if (idx < 0) {
        console.warn("[patch-gradle] could not find 'allprojects' block in build.gradle, skipping fix 3");
      } else {
        // Find the closing brace of the allprojects block
        // Insert after the closing brace of repositories within allprojects
        const afterAllprojects = content.indexOf("}", idx + marker.length + 1);
        // More robust: find the block and insert resolutionStrategy after repositories
        const insertion = `
  configurations.all {
    resolutionStrategy {
      force 'org.jetbrains:annotations:23.0.0'
    }
  }`;
        // Find where repositories block closes inside allprojects
        const reposBlockEnd = content.indexOf("}", idx + marker.length);
        // Actually, let's just find the line after the repositories closing and insert
        // Simpler approach: insert before the closing } of allprojects
        // Find the end of allprojects block
        let braceCount = 0;
        let allprojectsEnd = -1;
        for (let i = idx + marker.length; i < content.length; i++) {
          if (content[i] === "{") braceCount++;
          if (content[i] === "}") {
            braceCount--;
            if (braceCount === 0) {
              allprojectsEnd = i;
              break;
            }
          }
        }
        if (allprojectsEnd > 0) {
          content =
            content.slice(0, allprojectsEnd) +
            insertion +
            "\n" +
            content.slice(allprojectsEnd);
          writeFileSync(p, content);
          patched++;
          console.log("[patch-gradle] added annotations:23.0.0 force to build.gradle");
        } else {
          console.warn("[patch-gradle] could not locate end of allprojects block, skipping fix 3");
        }
      }
    }
  } else {
    console.warn("[patch-gradle] build.gradle not found, skipping fix 3");
  }
}

// --- Fix 4: RN settings.gradle.kts -> remove foojay-resolver-convention ---
{
  if (existsSync(rnSettingsKts)) {
    let content = readFileSync(rnSettingsKts, "utf8");
    if (content.includes("foojay-resolver-convention")) {
      content = content.replace(
        /plugins\s*\{[^}]*foojay-resolver-convention[^}]*\}/,
        "// foojay-resolver removed: requires Gradle 9.8+ (IBM_SEMERU), incompatible with pinned 9.5.0",
      );
      writeFileSync(rnSettingsKts, content);
      patched++;
      console.log("[patch-gradle] removed foojay-resolver from RN settings.gradle.kts");
    }
  } else {
    console.warn("[patch-gradle] RN settings.gradle.kts not found, skipping fix 4");
  }
}

// --- Fix 5: RN included build → jvmToolchain(17) → jvmToolchain(21) ---
// RN 0.83.6 hardcodes jvmToolchain(17) in 4 included-build modules. Most
// dev machines only have JDK 21; 21 is backwards-compatible with 17 code.
{
  const rnPluginDir = join(
    repoRoot,
    "node_modules/@react-native/gradle-plugin",
  );
  const buildFiles = [
    "react-native-gradle-plugin/build.gradle.kts",
    "settings-plugin/build.gradle.kts",
    "shared/build.gradle.kts",
    "shared-testutil/build.gradle.kts",
  ];
  for (const relPath of buildFiles) {
    const p = join(rnPluginDir, relPath);
    if (existsSync(p)) {
      let c = readFileSync(p, "utf8");
      if (c.includes("jvmToolchain(17)")) {
        c = c.replace(/jvmToolchain\(17\)/g, "jvmToolchain(21)");
        writeFileSync(p, c);
        patched++;
        console.log(`[patch-gradle] jvmToolchain 17->21 in ${relPath}`);
      }
    }
  }
}

// --- Fix 6: Add JDK installation paths for toolchain resolution ---
// The app build.gradle may require Java 17 toolchain while included builds
// use jvmToolchain(21). Add org.gradle.java.installations.paths to the
// global ~/.gradle/gradle.properties so all builds can find both JDKs.
{
  const gradleUserHome =
    process.env.GRADLE_USER_HOME ||
    join(process.env.USERPROFILE || process.env.HOME, ".gradle");
  const globalGradleProps = join(gradleUserHome, "gradle.properties");
  const jdkPaths = resolveJdkPaths().join(",");
  if (existsSync(globalGradleProps)) {
    let c = readFileSync(globalGradleProps, "utf8");
    if (!c.includes("org.gradle.java.installations.paths")) {
      c += `\n# Auto-added by patch-gradle: JDK paths for toolchain resolution\norg.gradle.java.installations.paths=${jdkPaths}\n`;
      writeFileSync(globalGradleProps, c);
      patched++;
      console.log("[patch-gradle] added JDK paths to global gradle.properties");
    } else {
      // Refresh stale paths: the machine may have moved its JDKs, and a
      // stale list makes the Java 17 toolchain unresolvable.
      const next = c.replace(
        /^org\.gradle\.java\.installations\.paths=.*$/m,
        `org.gradle.java.installations.paths=${jdkPaths}`,
      );
      if (next !== c) {
        writeFileSync(globalGradleProps, next);
        patched++;
        console.log("[patch-gradle] refreshed JDK paths in global gradle.properties");
      } else {
        console.log("[patch-gradle] global gradle.properties already has JDK paths");
      }
    }
  } else {
    const dir = dirname(globalGradleProps);
    if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
    writeFileSync(
      globalGradleProps,
      `# Auto-added by patch-gradle: JDK paths for toolchain resolution\norg.gradle.java.installations.paths=${jdkPaths}\n`,
    );
    patched++;
    console.log("[patch-gradle] created global gradle.properties with JDK paths");
  }
}

// Also clean up any stale tasks.withType blocks from previous fix 6 iterations
{
  const p = join(androidDir, "app", "build.gradle");
  if (existsSync(p)) {
    let c = readFileSync(p, "utf8");
    const cleanPattern = /\n\n?\/\/ Pinned to JDK 21.*?\}\n\s*\}\n\s*\}\n?\s*\}\n/g;
    const tasksWithPattern = /\n+\/\/ Pinned to JDK 21.*$/s;
    if (cleanPattern.test(c) || tasksWithPattern.test(c)) {
      c = c.replace(tasksWithPattern, "").trimEnd() + "\n";
      writeFileSync(p, c);
      patched++;
      console.log("[patch-gradle] removed stale tasks.withType block from app/build.gradle");
    }
  }
}

// --- Fix 7: included-build Kotlin scripts → skip metadata version check ---
// Gradle 9.5.0 embeds kotlin-stdlib 2.3.20 (metadata 2.3.0) while the RN/Expo
// Gradle plugins compile with Kotlin 2.1.20, which can only read metadata up to
// 2.2.0. Without the flag the included builds fail with "Module was compiled
// with an incompatible version of Kotlin". Scanning node_modules keeps this
// working across dependency bumps without hardcoding paths.
{
  const LINE_KTS = '  freeCompilerArgs.add("-Xskip-metadata-version-check")';
  const LINE_GROOVY = '  freeCompilerArgs += "-Xskip-metadata-version-check"';
  const seen = new Set();
  let touched = 0;

  const walk = (dir, depth) => {
    if (depth > 8) return;
    let entries;
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    for (const entry of entries) {
      const p = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name === "build" || entry.name === ".cxx" || entry.name === ".git") continue;
        walk(p, depth + 1);
      } else if (entry.name === "build.gradle.kts" || entry.name === "build.gradle") {
        let real;
        try {
          real = realpathSync(p);
        } catch {
          continue;
        }
        if (seen.has(real)) continue;
        seen.add(real);
        let c;
        try {
          c = readFileSync(real, "utf8");
        } catch {
          continue;
        }
        if (!/KotlinCompile|kotlinOptions\s*\{|compilerOptions\s*\{/.test(c)) continue;
        if (c.includes("Xskip-metadata-version-check")) continue;
        let next = c.replace(/(compilerOptions\s*\{)/g, (m) => `${m}\n${LINE_KTS}`);
        next = next.replace(/(kotlinOptions\s*\{)/g, (m) => `${m}\n${LINE_GROOVY}`);
        if (next !== c) {
          writeFileSync(real, next);
          touched++;
        }
      }
    }
  };

  walk(join(repoRoot, "node_modules"), 0);
  if (touched > 0) {
    patched++;
    console.log(`[patch-gradle] added -Xskip-metadata-version-check to ${touched} Kotlin build script(s)`);
  }
}

// --- Fix 8: shorten the CMake staging root (Windows 260-char limit) ---
// The default app/.cxx/... nesting pushes generated JNI object paths past
// CMAKE_OBJECT_PATH_MAX (250) on Windows; ninja then fails with
// "Filename longer than 260 characters". Point the staging dir at <repo>/.cxx.
{
  const p = join(androidDir, "app", "build.gradle");
  if (existsSync(p)) {
    let c = readFileSync(p, "utf8");
    if (!c.includes("buildStagingDirectory")) {
      const marker = "    androidResources {";
      const idx = c.indexOf(marker);
      const block =
        `    // Shorten the CMake staging root: the default app/.cxx/... nesting pushes\n` +
        `    // generated JNI object paths past CMAKE_OBJECT_PATH_MAX (250) on Windows,\n` +
        `    // which makes CMake mirror absolute paths and ninja then fails at 260.\n` +
        `    externalNativeBuild {\n` +
        `        cmake {\n` +
        `            buildStagingDirectory = file("$rootDir/../../../.cxx")\n` +
        `        }\n` +
        `    }\n`;
      if (idx < 0) {
        console.warn("[patch-gradle] could not find androidResources block in app/build.gradle, skipping fix 8");
      } else {
        c = c.slice(0, idx) + block + c.slice(idx);
        writeFileSync(p, c);
        patched++;
        console.log("[patch-gradle] pointed app CMake staging dir at <repo>/.cxx");
      }
    }
  } else {
    console.warn("[patch-gradle] app/build.gradle not found, skipping fix 8");
  }
}

// --- Fix 9: package fbjni's libc++_shared.so (startup crash, see the file) ---
// `expo prebuild` already applies this via the with-fbjni-libcxx config plugin;
// this keeps the override in place when a build reuses an existing android/ dir.
{
  const p = join(androidDir, "app", "build.gradle");
  const include = `apply from: file("../../scripts/android-fbjni-libcxx.gradle")\n`;
  if (existsSync(p)) {
    let c = readFileSync(p, "utf8");
    if (!c.includes("android-fbjni-libcxx.gradle")) {
      if (!c.endsWith("\n")) c += "\n";
      writeFileSync(p, c + include);
      patched++;
      console.log("[patch-gradle] applied fbjni libc++_shared.so override");
    }
  } else {
    console.warn("[patch-gradle] app/build.gradle not found, skipping fix 9");
  }
}

console.log(
  `[patch-gradle] ${patched} fix(es) applied, ${9 - patched} already in place.`,
);